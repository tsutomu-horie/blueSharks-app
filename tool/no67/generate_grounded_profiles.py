"""Foot/pelvis correspondences; originals remain unchanged. Requires Pillow, NumPy."""
from pathlib import Path
import csv,numpy as np
from PIL import Image
root=Path(__file__).resolve().parents[2]
records=list(csv.DictReader(open(Path(__file__).parent/'anchor-registration.csv')))
records=[r for r in records if r['pose'].startswith(('clean_','squat_','work_')) and not (r['pose'].startswith('work_') and r['pose'].endswith('done'))]
def measure(r):
 a=np.array(Image.open(root/r['asset'])).astype(int);opaque=a[:,:,3]>180
 dark=(a[:,:,:3]==[24,83,149]).all(2)&opaque
 blue=(a[:,:,:3]==[82,156,193]).all(2)&opaque
 floor=int(np.where(dark)[0].max());axes=[]
 for y in range(floor-26,floor-17):
  xs=np.where(dark[y])[0]
  runs=[v for v in np.split(xs,np.where(np.diff(xs)>1)[0]+1) if len(v)>12]
  if len(runs)>=2:
   runs=sorted(sorted(runs,key=len,reverse=True)[:2],key=lambda v:v[0]);axes.append((runs[0][-1]+runs[1][0])/2)
 axis=float(np.median(axes)) if axes else float(r['sourceAnchor'])
 bottom=int(np.where(blue)[0].max());centers=[]
 for y in range(bottom-12,bottom-3):
  xs=np.where(blue[y])[0]
  if len(xs)>4:centers.append((xs.min()+xs.max())/2)
 pelvis=float(np.median(centers)) if centers else float(r['sourceAnchor'])
 if r['pose'].startswith('work_'):
  top=int(np.where(blue)[0].min());centers=[]
  for y in range(top+20,top+65):
   xs=np.where(blue[y])[0]
   if len(xs)>10:centers.append((xs.min()+xs.max())/2)
  pelvis=float(np.median(centers)) if centers else float(r['sourceAnchor']);floor=bottom+1
  rows={}

 labcolors=np.array([(127,172,166),(223,224,153),(175,170,144)])
 # Restrict reconstruction to the broom's original color mask.
 allcolors=np.array([(199,231,241),(128,205,232),(82,156,193),(24,83,149),(0,163,218),(245,249,240),(6,41,83),(175,102,162),(136,189,63),*labcolors])
 lab=((a[:,:,:3,None]-allcolors.T[None,None,:,:])**2).sum(2).argmin(2)
 if r['pose'].startswith('clean_'):
  broom=np.isin(lab,[9,10,11])&(a[:,:,3]>0)
  for y,x in zip(*np.where(broom)):
   other=round(2*axis-1-x)
   if y>=bottom-12 and 0<=other<a.shape[1] and dark[y,other]:dark[y,x]=True
 rows={}
 for y in range(max(bottom+2,floor-80),floor+1):
  xs=np.where(dark[y])[0];extent=60 if y>=floor-20 else 38;xs=xs[abs(xs-axis)<=extent];left=xs[xs<axis-2];right=xs[xs>axis+2]
  if len(left)>2 and len(right)>2:rows[y]=[float(left.min()),float(left.max()+1),float(right.min()),float(right.max()+1)]
 return dict(a=a,floor=floor,axis=axis,pelvis=pelvis,waist=(top+65 if r['pose'].startswith('work_') else bottom-12),rows=( {} if r['pose'].startswith('work_') else rows),pad=float(r['oldCanvasAnchor'])-float(r['sourceAnchor']))
ms={r['asset']:measure(r) for r in records}
text='// Generated by tool/no67/generate_grounded_profiles.py from original PNGs.\nclass GroundedProfile {\n const GroundedProfile(this.first,this.upperX,this.axis,this.floor,this.targetFloor,this.waist,this.targetWidth,this.targetHeight,this.rows);\n final String first; final double upperX,axis,floor,targetFloor,waist,targetWidth,targetHeight; final List<double> rows;\n}\nconst groundedProfiles=<String,GroundedProfile>{\n'
for r in records:
 first=next(z for z in records if z['body']==r['body'] and z['pose']==r['pose'].split('_')[0]+'_1')
 m=ms[r['asset']];f=ms[first['asset']]
 dx=f['pelvis']+f['pad']-m['pelvis']-m['pad'];rows=[]
 for sy in sorted(m['rows']):
  ty=sy-m['floor']+f['floor']
  if ty in f['rows']:rows += [float(sy),*m['rows'][sy],*f['rows'][ty]]
 vals=','.join(str(v) for v in rows)
 text+=repr(r['asset'])+':GroundedProfile('+repr(first['asset'])+f",{dx},{m['axis']},{m['floor']},{f['floor']},{m['waist']},{f['a'].shape[1]},{f['a'].shape[0]},[{vals}]),\n"
text+='};\n';(root/'lib/presentation/training_game/sametaroh_grounded_profiles.dart').write_text(text)
